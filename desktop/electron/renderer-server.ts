import crypto from 'node:crypto';
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import type { AddressInfo } from 'node:net';
import type { IncomingMessage, ServerResponse } from 'node:http';

/**
 * Serve the packaged renderer from loopback and reverse-proxy `/api/*` to the
 * supervised `agent-toolkit serve`. Loading via file:// stamps Origin: null and
 * strips X-Atk-Desktop; loading from a different loopback port trips CORS
 * because serve emits no Access-Control-Allow-Origin. Same-origin static+proxy
 * keeps the security model (no browser CORS) while Desktop works.
 *
 * Trust boundary (fail-closed): the loopback port is reachable by any local
 * process and by browser pages that can address loopback, so port secrecy is
 * not authentication. Every `/api/*` and `/v1/*` request must carry the
 * per-launch capability in `x-veasel-proxy` (generated by the main process,
 * injected via session.webRequest for this exact origin, never exposed to
 * renderer JS, URLs, logs, or persisted state), arrive with this server's own
 * Host, carry no foreign Origin, and not be marked cross-site. Only after
 * that gate does the proxy stamp `x-atk-desktop: '1'`; the original
 * Origin/Sec-Fetch headers are forwarded untouched so backend gates keep
 * their meaning.
 */

export const PROXY_TOKEN_HEADER = 'x-veasel-proxy';
const MAX_PROXY_BODY_BYTES = 16 * 1024 * 1024;

function tokenMatches(supplied: string | string[] | undefined, expected: string): boolean {
  if (typeof supplied !== 'string') return false;
  const a = Buffer.from(supplied);
  const b = Buffer.from(expected);
  return a.length === b.length && crypto.timingSafeEqual(a, b);
}

const TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.json': 'application/json',
  '.map': 'application/json',
};

function safeJoin(root: string, requestPath: string): string | null {
  const rawPath = (requestPath.split('?')[0] ?? '/').split('#')[0] ?? '/';
  let decoded: string;
  try {
    decoded = decodeURIComponent(rawPath);
  } catch {
    return null;
  }
  // NUL truncates paths in native APIs; backslash is a separator on Windows.
  if (decoded.includes('\0') || decoded.includes('\\') || rawPath.includes('\\')) return null;
  const relative = decoded === '/' ? 'index.html' : decoded.replace(/^\/+/, '');
  const resolved = path.resolve(root, relative);
  if (resolved !== root && !resolved.startsWith(root + path.sep)) return null;
  return resolved;
}

function proxyApi(
  req: IncomingMessage,
  res: ServerResponse,
  backendBase: string,
): void {
  const target = new URL(req.url ?? '/', backendBase);
  const headers: http.OutgoingHttpHeaders = { ...req.headers, host: target.host };
  // The capability and any caller-supplied trust stamp never cross the proxy:
  // the gate has already authenticated this request, and the backend must see
  // only the stamp this proxy issues. Origin/Sec-Fetch are forwarded as sent
  // so backend gates keep their meaning (no laundering).
  delete headers[PROXY_TOKEN_HEADER];
  delete headers['x-atk-desktop'];
  headers['x-atk-desktop'] = '1';

  const upstream = http.request(
    {
      protocol: target.protocol,
      hostname: target.hostname,
      port: target.port,
      path: `${target.pathname}${target.search}`,
      method: req.method,
      headers,
    },
    (upstreamRes) => {
      upstreamRes.on('error', () => {
        // A downstream close can destroy the upstream request while its
        // response stream is still active. Consume that stream error so it
        // cannot become an uncaught exception in the Desktop main process.
        if (res.destroyed || res.writableEnded) return;
        if (!res.headersSent) {
          res.writeHead(502, { 'content-type': 'application/json' });
          res.end(JSON.stringify({ ok: false, error: 'backend response stream failed' }));
        } else {
          res.destroy();
        }
      });
      res.writeHead(upstreamRes.statusCode ?? 502, upstreamRes.headers);
      upstreamRes.pipe(res);
    },
  );
  upstream.on('error', (error) => {
    if (!res.headersSent) res.writeHead(502, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ ok: false, error: `backend proxy failed: ${error.message}` }));
  });
  res.once('close', () => {
    // EventSource keeps proxied requests open. If Desktop closes, abort the
    // upstream request too instead of leaving a backend socket orphaned.
    if (!upstream.destroyed) upstream.destroy();
  });
  let bodyBytes = 0;
  req.on('data', (chunk: Buffer) => {
    bodyBytes += chunk.length;
    if (bodyBytes > MAX_PROXY_BODY_BYTES) {
      upstream.destroy();
      if (!res.headersSent) res.writeHead(413, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ ok: false, error: 'request body too large' }));
    }
  });
  req.pipe(upstream);
}

export interface RendererServer {
  /** Same-origin base the renderer should use for both UI and `/api` (no trailing slash). */
  url: string;
  /**
   * Per-launch capability for the `/api` + `/v1` proxy gate. Main-process
   * only: never expose it to renderer JS, URLs, logs, or persisted state.
   */
  proxyToken: string;
  setBackendTarget: (backendBaseUrl: string | null) => void;
  close: () => Promise<void>;
}

export interface RendererServerOptions {
  /** Test seam; production callers omit it and get a fresh random token. */
  proxyToken?: string;
}

const STATIC_HARDENING_HEADERS = {
  'x-content-type-options': 'nosniff',
  'content-security-policy': "frame-ancestors 'none'",
} as const;

export async function startRendererServer(
  distDir: string,
  options: RendererServerOptions = {},
): Promise<RendererServer> {
  const root = path.resolve(distDir);
  const realRoot = fs.realpathSync(root);
  if (!fs.existsSync(path.join(root, 'index.html'))) {
    throw new Error(`Renderer dist missing index.html at ${root}`);
  }
  const proxyToken = options.proxyToken ?? crypto.randomBytes(32).toString('base64url');

  let backendBase: string | null = null;
  let ownAuthority = '';

  const rejectForbidden = (res: ServerResponse): void => {
    res.writeHead(403, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ ok: false, error: 'forbidden' }));
  };

  const sendText = (res: ServerResponse, status: number, text: string): void => {
    if (res.headersSent || res.writableEnded) return;
    res.writeHead(status, { 'content-type': 'text/plain; charset=utf-8' }).end(text);
  };

  /** Read a file only if its symlink-resolved path stays inside the real root. */
  const readContained = (
    file: string,
    cb: (error: NodeJS.ErrnoException | null, data?: Buffer, real?: string) => void,
  ): void => {
    // Lexical containment first: no filesystem call ever sees a path outside
    // the served root. The realpath check below then catches symlink escapes.
    const lexical = path.resolve(file);
    if (lexical !== root && !lexical.startsWith(root + path.sep)) {
      const denied: NodeJS.ErrnoException = new Error('outside root');
      denied.code = 'EOUTSIDE';
      return cb(denied);
    }
    fs.realpath(lexical, (rpError, real) => {
      if (rpError) return cb(rpError);
      if (real !== realRoot && !real.startsWith(realRoot + path.sep)) {
        const denied: NodeJS.ErrnoException = new Error('outside root');
        denied.code = 'EOUTSIDE';
        return cb(denied);
      }
      fs.readFile(real, (error, data) => cb(error, data, real));
    });
  };

  const handle = (req: IncomingMessage, res: ServerResponse): void => {
    const url = req.url ?? '/';
    // DNS-rebinding guard for every request, static included: only this
    // server's own loopback authority is accepted (absent Host fails closed).
    if (req.headers.host !== ownAuthority) return rejectForbidden(res);
    // Veasel API surface is proxied same-origin too (no CORS, no LAN):
    // the renderer only ever talks to this loopback server.
    if (url === '/api' || url.startsWith('/api/') || url === '/v1' || url.startsWith('/v1/')) {
      // Fail-closed gate, before any backend contact or readiness disclosure:
      // capability, own Host (DNS-rebinding), own Origin when present, and
      // never a cross-site browser context.
      if (!tokenMatches(req.headers[PROXY_TOKEN_HEADER], proxyToken)) return rejectForbidden(res);
      const origin = req.headers.origin;
      if (origin !== undefined && origin !== `http://${ownAuthority}`) return rejectForbidden(res);
      if (req.headers['sec-fetch-site'] === 'cross-site') return rejectForbidden(res);
      const declaredLength = Number(req.headers['content-length'] ?? 0);
      if (Number.isFinite(declaredLength) && declaredLength > MAX_PROXY_BODY_BYTES) {
        res.writeHead(413, { 'content-type': 'application/json' });
        res.end(JSON.stringify({ ok: false, error: 'request body too large' }));
        return;
      }
      if (!backendBase) {
        res.writeHead(503, { 'content-type': 'application/json' });
        res.end(JSON.stringify({ ok: false, error: 'backend not ready' }));
        return;
      }
      proxyApi(req, res, backendBase);
      return;
    }

    const filePath = safeJoin(root, url);
    if (!filePath) {
      sendText(res, 403, 'forbidden');
      return;
    }
    readContained(filePath, (error, data, real) => {
      if (error) {
        if (error.code === 'EOUTSIDE') return sendText(res, 403, 'forbidden');
        if (error.code === 'ENOENT' || error.code === 'ENOTDIR') {
          readContained(path.join(root, 'index.html'), (fallbackError, html) => {
            if (fallbackError || !html) return sendText(res, 404, 'not found');
            res.writeHead(200, { 'content-type': TYPES['.html'], ...STATIC_HARDENING_HEADERS }).end(html);
          });
          return;
        }
        // EISDIR, EACCES, ENAMETOOLONG, ...: no detail disclosure.
        return sendText(res, error.code === 'ENAMETOOLONG' ? 414 : 404, 'not found');
      }
      const type = TYPES[path.extname(real ?? filePath).toLowerCase()] ?? 'application/octet-stream';
      res.writeHead(200, { 'content-type': type, 'cache-control': 'no-cache', ...STATIC_HARDENING_HEADERS }).end(data);
    });
  };

  const server = http.createServer((req, res) => {
    // Last-resort guard: nothing may throw out of the handler into the
    // Electron main process.
    try {
      handle(req, res);
    } catch {
      if (!res.headersSent) sendText(res, 500, 'error');
      else res.destroy();
    }
  });
  server.on('clientError', (_error, socket) => {
    if (socket.writable) socket.end('HTTP/1.1 400 Bad Request\r\nConnection: close\r\n\r\n');
    else socket.destroy();
  });

  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => {
      ownAuthority = `127.0.0.1:${(server.address() as AddressInfo).port}`;
      resolve();
    });
  });

  const address = server.address() as AddressInfo;
  const url = `http://127.0.0.1:${address.port}`;
  return {
    url,
    proxyToken,
    setBackendTarget: (next) => {
      backendBase = next ? next.replace(/\/$/, '') : null;
    },
    close: () =>
      new Promise((resolve, reject) => {
        server.close((error) => (error ? reject(error) : resolve()));
        // Stop accepting first, then force active EventSource/API connections
        // closed so the callback cannot wait forever during app shutdown.
        server.closeAllConnections();
      }),
  };
}
