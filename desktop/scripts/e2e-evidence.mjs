#!/usr/bin/env node
// Builds docs/desktop/E2E_EVIDENCE.md from REAL run output only:
//   evidence.jsonl  (written by e2e/electron/evidence.ts during the run)
//   results.json    (Playwright JSON reporter output of the same run)
// A journey with no result line is reported as NOT RUN; nothing is inferred.
//
// usage: node scripts/e2e-evidence.mjs <evidence.jsonl> <results.json> <backend-binary> <out.md>
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const [evidencePath, resultsPath, binary, out] = process.argv.slice(2);
const PACKAGED_START = '<!-- PACKAGED_GUI_EVIDENCE_START -->';
const PACKAGED_END = '<!-- PACKAGED_GUI_EVIDENCE_END -->';

function renderPackagedEvidence(outputPath) {
  const evidenceDir = path.join(path.dirname(path.resolve(outputPath)), 'evidence');
  if (!fs.existsSync(evidenceDir)) return '';
  const records = fs
    .readdirSync(evidenceDir)
    .filter((name) => name.startsWith('claude-packaged-') && name.endsWith('.json'))
    .sort()
    .map((name) => ({ name, record: JSON.parse(fs.readFileSync(`${evidenceDir}/${name}`, 'utf8')) }));
  if (records.length === 0) return '';
  const rows = records.map(({ name, record }) => {
    const classification = Array.isArray(record.classification) ? record.classification.join(', ') : 'UNCLASSIFIED';
    const test = record.independent_check?.after_turn ?? 'No independent test recorded';
    const driver = record.automation_driver?.status ?? 'No driver caveat recorded';
    return `| ${record.captured_at ?? 'unknown'} | ${record.provider?.id ?? 'unknown'} | ${record.artifact?.release ?? 'unknown'} | ${classification} | ${test} | ${driver} | [${name}](evidence/${name}) |`;
  });
  return `${PACKAGED_START}\n## Packaged GUI real-provider journeys\n\nGenerated from sanitized records in docs/desktop/evidence/. It complements the deterministic journey table above; it does not change its verdicts.\n\n| Date | Provider | Release | Classification | Independent check | Driver note | Provenance |\n|------|----------|---------|----------------|-----------------|-------------|------------|\n${rows.join('\n')}\n${PACKAGED_END}`;
}

if (process.argv[2] === '--refresh-packaged') {
  const outputPath = process.argv[3];
  if (!outputPath || !fs.existsSync(outputPath)) {
    console.error('usage: e2e-evidence.mjs --refresh-packaged <existing-output.md>');
    process.exit(2);
  }
  const existing = fs.readFileSync(outputPath, 'utf8');
  const base = existing.includes(PACKAGED_START)
    ? existing.slice(0, existing.indexOf(PACKAGED_START)).trimEnd()
    : existing.trimEnd();
  const packaged = renderPackagedEvidence(outputPath);
  fs.writeFileSync(outputPath, `${base}${packaged ? `\n\n${packaged}\n` : '\n'}`);
  console.log(`refreshed packaged evidence in ${outputPath}`);
  process.exit(0);
}

if (!evidencePath || !resultsPath || !binary || !out) {
  console.error('usage: e2e-evidence.mjs <evidence.jsonl> <results.json> <backend-binary> <out.md>');
  process.exit(2);
}
const evidence = fs.existsSync(evidencePath)
  ? fs
      .readFileSync(evidencePath, 'utf8')
      .split('\n')
      .filter(Boolean)
      .map((line) => JSON.parse(line))
  : [];
const results = JSON.parse(fs.readFileSync(resultsPath, 'utf8'));
const specs = [];
const walk = (suite) => {
  for (const spec of suite.specs ?? []) specs.push(spec);
  for (const child of suite.suites ?? []) walk(child);
};
for (const suite of results.suites ?? []) walk(suite);

const sha = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const binarySha = crypto.createHash('sha256').update(fs.readFileSync(binary)).digest('hex');
const journeyIds = [
  'J1',
  'J2',
  'J3',
  'J3b',
  'J3c',
  'J4',
  'J4b',
  'J4c',
  'J5',
  'J6',
  'J7',
  'J8',
  'J8b',
  'J9',
  'J10',
  'J11',
];

const rows = journeyIds.map((id) => {
  const spec = specs.find((candidate) => candidate.title.startsWith(`${id} `));
  const test = spec?.tests?.[0];
  const status = test?.status ?? 'not run';
  const verdict =
    test === undefined
      ? 'NOT RUN'
      : test.expectedStatus === 'skipped' || status === 'skipped'
        ? 'FIXME/SKIPPED'
        : status === 'expected' && test.expectedStatus === 'failed'
          ? 'FAIL (known product bug; test.fail)'
          : status === 'expected'
            ? 'PASS'
            : status === 'unexpected'
              ? 'FAIL'
              : status === 'flaky'
                ? 'FLAKY'
                : status.toUpperCase();
  const entry = evidence.find((candidate) => candidate.journey === id);
  const oracle = entry?.oracle ?? '(no oracle evidence recorded)';
  return `| ${id} | ${spec?.title.replace(/\|/g, '/') ?? '-'} | ${oracle.replace(/\|/g, '/')} | ${verdict} |`;
});

const generated = `# Desktop Focus journeys: E2E evidence

Generated by \`desktop/scripts/e2e-evidence.mjs\` from a real run. Do not edit by hand.

- Commit: \`${sha}\`
- Backend binary sha256: \`${binarySha}\`
- Generated: ${new Date().toISOString()}

| Journey | Title | Oracle | Result |
|---------|-------|--------|--------|
${rows.join('\n')}
`;
const packaged = renderPackagedEvidence(out);
fs.writeFileSync(out, `${generated}${packaged ? `\n${packaged}\n` : ''}`);
console.log(`wrote ${out}`);
