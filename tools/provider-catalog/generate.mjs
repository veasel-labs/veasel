import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import path from "node:path"

const directory = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(directory, "../..")
const inputPath = path.join(directory, "providers.json")
const outputPath = path.join(root, "model_settings.generated.v")
const docsPath = path.join(root, "docs/PROVIDERS.md")
const selected = JSON.parse(await readFile(inputPath, "utf8"))

function validate() {
  if (!/^[a-f0-9]{40}$/.test(selected.source?.commit ?? "")) {
    throw new Error("provider catalog must pin a full Models.dev commit SHA")
  }
  if (selected.source?.repository !== "https://github.com/anomalyco/models.dev") {
    throw new Error("unexpected provider catalog source")
  }
  if (!Array.isArray(selected.providers) || selected.providers.length < 75) {
    throw new Error("provider catalog must retain at least 75 endpoint presets")
  }
  if (selected.providers.filter((provider) => provider.source === "models.dev").length !== 36) {
    throw new Error("expected exactly 36 explicitly selected Models.dev presets")
  }
  const ids = new Set()
  for (const provider of selected.providers) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(provider.id)) {
      throw new Error(`invalid provider ID: ${provider.id}`)
    }
    if (ids.has(provider.id)) throw new Error(`duplicate provider ID: ${provider.id}`)
    ids.add(provider.id)
    if (!provider.name || !provider.protocol || !provider.description || !provider.api) {
      throw new Error(`incomplete provider metadata: ${provider.id}`)
    }
    if (provider.requires_api_key && !/^[A-Z0-9_]+$/.test(provider.environment_key)) {
      throw new Error(`invalid environment variable for ${provider.id}`)
    }
    if (provider.source === "models.dev") {
      if (provider.protocol !== "openai-compatible") {
        throw new Error(`Models.dev compatible preset has a non-compatible protocol: ${provider.id}`)
      }
      if (provider.models_dev_source !== `providers/${provider.id}/provider.toml`) {
        throw new Error(`unexpected Models.dev path for ${provider.id}`)
      }
      if (!provider.documentation_url) throw new Error(`missing provider documentation: ${provider.id}`)
    }
    const api = new URL(provider.api)
    if (api.protocol !== "https:" && !(api.protocol === "http:" && ["127.0.0.1", "localhost", "[::1]"].includes(api.hostname))) {
      throw new Error(`invalid API URL protocol for ${provider.id}`)
    }
    if (api.username || api.password || api.search || api.hash || /[{}$]/.test(provider.api)) {
      throw new Error(`unresolved or unsafe API URL for ${provider.id}`)
    }
    if (provider.documentation_url) {
      const docs = new URL(provider.documentation_url)
      if (docs.protocol !== "https:" || docs.username || docs.password) {
        throw new Error(`invalid documentation URL for ${provider.id}`)
      }
    }
  }
}

function vString(value) {
  return `'${value.replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("$", "\\$")}'`
}

function renderV() {
  const providers = [...selected.providers].sort((a, b) => a.id.localeCompare(b.id))
  const idParts = providers.map((provider) => vString(provider.id))
  const idLines = []
  let idLine = "const supported_model_providers = ["
  for (const [index, id] of idParts.entries()) {
    const part = `${id}${index < idParts.length - 1 ? ", " : ""}`
    if (idLine.length + part.length > 103) {
      idLines.push(idLine.trimEnd())
      idLine = `\t${part}`
    } else {
      idLine += part
    }
  }
  idLines.push(`${idLine}]`)
  const entries = providers.map((provider) => `\t\tModelProviderInfo{ id: ${vString(provider.id)}, name: ${vString(provider.name)}, description: ${vString(provider.description)}, protocol: ${vString(provider.protocol)}, base_url: ${vString(provider.api)}, environment_key: ${vString(provider.environment_key)}, documentation_url: ${vString(provider.documentation_url)}, requires_api_key: ${provider.requires_api_key} },`).join("\n")
  return `// Generated by tools/provider-catalog/generate.mjs. Do not edit by hand.\n// Models.dev data: ${selected.source.repository}/tree/${selected.source.commit}\nmodule main\n\n${idLines.join("\n")}\n\nfn model_provider_catalog() []ModelProviderInfo {\n\treturn [\n${entries}\n\t]\n}\n`
}

function renderDocs() {
  const providers = [...selected.providers].sort((a, b) => a.name.localeCompare(b.name))
  const rows = providers.map((provider) => {
    const docs = provider.documentation_url ? `[Documentation](${provider.documentation_url})` : "—"
    const credential = provider.requires_api_key ? provider.environment_key : "Not required by preset"
    return `| ${provider.name} | ${provider.id} | ${provider.protocol} | ${provider.api} | ${credential} | ${docs} |`
  }).join("\n")
  const modeldevCount = providers.filter((provider) => provider.source === "models.dev").length
  return `<!-- Generated by tools/provider-catalog/generate.mjs. Do not edit the provider table by hand. -->\n# Model providers\n\nVeasel ships ${providers.length} provider presets in the V binary. This count describes endpoint presets, not independent SDKs or equivalent feature coverage. Four protocol adapters currently power them: OpenAI Chat Completions, OpenAI Responses, Anthropic Messages, and Google Gemini. The ${modeldevCount} entries sourced from Models.dev use Veasel's shared OpenAI-compatible Chat Completions transport; provider-specific SDK features, authentication schemes, and model capabilities are not implied. Meta Model API uses the Responses transport with stateless encrypted reasoning replay for tool loops.\n\nThe TUI fetches this catalog from the local Veasel server. Press s on the home screen or use /models in a session to search providers. Choose a model ID from live discovery when available, or enter one manually. Credentials can be provided with the listed environment variable or saved in Veasel settings.\n\nModels.dev entries are selected from [anomalyco/models.dev](https://github.com/anomalyco/models.dev), an MIT-licensed community-maintained catalog used by OpenCode. Veasel pins the source revision to [${selected.source.commit}](${selected.source.repository}/tree/${selected.source.commit}); the selected base URLs, credential variable names, and documentation links are checked into tools/provider-catalog/providers.json. The V source and this page are generated from that file. No Models.dev network request, Node runtime, or other provider package is needed by Veasel after compilation.\n\nThe Models.dev selection filter requires its OpenAI-compatible adapter marker, an HTTPS API base URL, exactly one credential variable, and no unresolved URL template. Presets are not live-availability guarantees; endpoint access, account eligibility, model IDs, regional settings, and tool support depend on each provider. The openai-compatible preset remains available for custom endpoints. Local presets target loopback by default. Meta's live model discovery lists the models enabled for the configured Model API account; the documented coding choices include Muse Wonder 1.0 and Muse Spark 1.3. Veasel currently sends text and tool schemas, uses high reasoning with automatic summaries, and caps each model response at 4,096 output tokens.\n\n| Provider | ID | Protocol used by Veasel | Default API endpoint | Credential | Reference |\n|---|---|---|---|---|---|\n${rows}\n`
}

validate()
const outputs = [[outputPath, renderV()], [docsPath, renderDocs()]]
if (process.argv.includes("--check")) {
  for (const [filename, expected] of outputs) {
    const actual = await readFile(filename, "utf8").catch(() => "")
    if (actual !== expected) {
      console.error(`${path.relative(root, filename)} is stale; run node tools/provider-catalog/generate.mjs`)
      process.exitCode = 1
    }
  }
} else {
  for (const [filename, content] of outputs) await writeFile(filename, content)
}
